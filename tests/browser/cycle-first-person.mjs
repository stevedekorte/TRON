import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:750},reducedMotion:'reduce'}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/jev/**',r=>r.fulfill({status:503,body:'{}'}));
 await page.goto('http://localhost:5173/');await page.waitForFunction(()=>window.__tron&&!document.querySelector('#start-cycles').disabled);
 await page.locator('#start-cycles').click();await page.waitForFunction(()=>__tron.state.cycleRace?.phase==='racing',null,{timeout:120000});
 await page.evaluate(()=>{const r=__tron.state.cycleRace;r.arenaPaused=true;__tron.place({cycleRace:r});});
 await page.evaluate(()=>{const r=__tron.state.cycleRace;r.cycles[r.playerId].human=true;__tron.place({cycleRace:r});});
 await page.waitForFunction(()=>__tron.state.cycleRendering.playerStripe===1);
 await page.keyboard.press('KeyP');
 await page.waitForFunction(()=>__tron.state.camera.cycleFirstPersonMix>.98);
 assert.equal(await page.evaluate(()=>__tron.state.camera.cycleFirstPerson),true);
 assert(Math.abs((await page.evaluate(()=>__tron.state.camera.y))-1.3)<.1);
 assert(Math.abs((await page.evaluate(()=>__tron.state.camera.fov))-85)<1,'wide first-person field of view');
 await page.waitForTimeout(400);
 const shell=await page.evaluate(()=>__tron.state.cycleRendering.playerMaterials);
 assert(shell.length&&shell.every(m=>m.window?m.opacity<.01:Math.abs(m.opacity-.2)<.01),`body at 0.2, windows hidden: ${JSON.stringify(shell)}`);
 assert.equal(await page.evaluate(()=>__tron.state.cycleRendering.playerStripe),0,'own human stripe hidden in first person');
 const outline=await page.evaluate(()=>__tron.state.cycleRendering.cockpitOutline);
 assert(outline?.visible,'cockpit outline shown in first person');
 assert(Math.abs(outline.opacity-.5)<.01,`outline opacity ${outline.opacity}`);
 assert(outline.segments>50&&outline.segments<400,`sparse outline, ${outline.segments} segments`);
 await page.screenshot({path:'test-results/cycle-first-person.png'});
 await page.keyboard.press('KeyP');await page.waitForFunction(()=>__tron.state.camera.cycleFirstPersonMix<.01);
 assert.equal(await page.evaluate(()=>__tron.state.camera.cycleFirstPerson),false);
 assert(Math.abs((await page.evaluate(()=>__tron.state.camera.fov))-63)<1,'chase field of view restored');
 await page.waitForFunction(()=>!__tron.state.cycleRendering.cockpitOutline.visible);
 assert((await page.evaluate(()=>__tron.state.cycleRendering.playerMaterials)).every(m=>m.opacity===1),'materials restored after exit');
 assert.deepEqual(errors,[]);console.log('P toggles smooth cockpit entry and return; cockpit height and glowing outline, 0.2 body shell, hidden windows and hidden own stripe verified.');
}finally{await browser.close();}
